#!/usr/bin/env bash
# amplai-foundry deterministic evaluator for the AMPLAI Loop Runtime.
# cortex main 3a3eb46b 에서 이식했다 (D-046). semantic profile 은 제외했다.
#
# Exit codes:
#   0 PASS
#   1 FAIL       — repair and run again
#   2 UNAVAILABLE/CONFIG ERROR — fixing code cannot solve this
#   3 ESCALATE   — same failure signature reached MAX consecutive attempts
#
# Layers:
#   project verifier profile  .ai-team/verifiers/registry.json
#   slice contract            generated tasks.md -> Slice Eval commands
#
# Bash 3.2 compatible (mac default): no mapfile or associative arrays.
set -uo pipefail

REPO="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
cd "$REPO" || exit 2

SLICE=""
TASKS=""
FEATURE=""
PROFILE=""
FULL=0
LIST=0
MAX_ATTEMPTS="${EVAL_MAX_ATTEMPTS:-3}"
MAX_EXPLICIT=0
EVIDENCE_DIR="${EVAL_EVIDENCE_DIR:-.specify/eval}"

usage() {
  cat <<'EOF'
Usage:
  scripts/eval.sh [--feature DIR | --tasks FILE] [--slice ID]
                  [--profile fast|commit|standard|runtime|full|v2] [--full]
                  [--max-attempts N]
  scripts/eval.sh [--feature DIR | --tasks FILE] --list-slices

Resolution order for tasks.md:
  --tasks -> --feature/tasks.md -> .specify/feature.json -> one unique generated tasks.md

--full is a compatibility alias: use work-contract.json verification.profile when
present, otherwise profile=full.
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --slice) SLICE="${2:-}"; shift 2 ;;
    --tasks) TASKS="${2:-}"; shift 2 ;;
    --feature) FEATURE="${2:-}"; shift 2 ;;
    --profile) PROFILE="${2:-}"; shift 2 ;;
    --full) FULL=1; shift ;;
    --list-slices) LIST=1; shift ;;
    --max-attempts) MAX_ATTEMPTS="${2:-3}"; MAX_EXPLICIT=1; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "eval.sh: unknown option $1" >&2; usage >&2; exit 2 ;;
  esac
done

case "$MAX_ATTEMPTS" in
  ''|*[!0-9]*) echo "eval.sh: --max-attempts must be an integer" >&2; exit 2 ;;
esac
[ "$MAX_ATTEMPTS" -ge 1 ] 2>/dev/null || { echo "eval.sh: max attempts must be >= 1" >&2; exit 2; }

resolve_feature_from_marker() {
  [ -f .specify/feature.json ] || return 0
  python3 - <<'PY' 2>/dev/null || true
import json
try:
    value = json.load(open('.specify/feature.json', encoding='utf-8'))
    print(value.get('feature_directory') or '')
except Exception:
    pass
PY
}

is_generated_tasks() {
  grep -q '<!-- GENERATED BY .specify/scripts/taskify_to_tasks_md.py' "$1" 2>/dev/null
}

find_tasks() {
  if [ -n "$TASKS" ]; then
    printf '%s\n' "$TASKS"
    return
  fi
  if [ -n "$FEATURE" ]; then
    if [ -f "$FEATURE" ]; then
      printf '%s\n' "$FEATURE"
    else
      printf '%s/tasks.md\n' "${FEATURE%/}"
    fi
    return
  fi
  marker="$(resolve_feature_from_marker)"
  if [ -n "$marker" ]; then
    printf '%s/tasks.md\n' "${marker%/}"
    return
  fi

  # Never choose "most recently edited"; that silently changes the work item.
  # Use the only generated tasks.md if the repository has exactly one.
  tmp="${TMPDIR:-/tmp}/amplai-eval-tasks.$$"
  : > "$tmp"
  if [ -d specs ]; then
    find specs -maxdepth 4 -name tasks.md -type f 2>/dev/null | while IFS= read -r path; do
      if is_generated_tasks "$path"; then printf '%s\n' "$path"; fi
    done > "$tmp"
  fi
  count="$(wc -l < "$tmp" | tr -d ' ')"
  if [ "$count" = 1 ]; then
    cat "$tmp"
  fi
  rm -f "$tmp"
}

extract_section() {
  awk -v slice="$2" -v section="$3" '
    /^## Slice / { inslice = ($3 == slice); insec = 0; next }
    /^## /       { inslice = 0; insec = 0; next }
    !inslice     { next }
    $0 == section ":" { insec = 1; next }
    /^[A-Za-z][A-Za-z ]*:[ \t]*$/ { insec = 0; next }
    insec && /^- / { sub(/^- /, ""); print }
  ' "$1"
}

list_slices() {
  grep -E '^## Slice ' "$1" 2>/dev/null | sed 's/^## Slice /  /'
}

TASKS_FILE="$(find_tasks)"
if [ -n "$TASKS_FILE" ]; then
  case "$TASKS_FILE" in
    /*) : ;;
    *) TASKS_FILE="$REPO/$TASKS_FILE" ;;
  esac
  tasks_dir="$(dirname "$TASKS_FILE")"
  if [ -d "$tasks_dir" ]; then
    TASKS_FILE="$(cd "$tasks_dir" 2>/dev/null && pwd)/$(basename "$TASKS_FILE")"
  fi
fi

if [ "$LIST" = 1 ]; then
  if [ -z "$TASKS_FILE" ] || [ ! -f "$TASKS_FILE" ]; then
    echo "eval.sh: tasks.md를 하나로 결정하지 못했다. --feature 또는 --tasks를 지정한다." >&2
    exit 2
  fi
  echo "slices in ${TASKS_FILE#$REPO/}:"
  list_slices "$TASKS_FILE"
  exit 0
fi

FEATURE_DIR=""
if [ -n "$TASKS_FILE" ] && [ -f "$TASKS_FILE" ]; then
  FEATURE_DIR="$(dirname "$TASKS_FILE")"
elif [ -n "$FEATURE" ] && [ -d "$FEATURE" ]; then
  FEATURE_DIR="$(cd "$FEATURE" && pwd)"
fi
CONTRACT=""
if [ -n "$FEATURE_DIR" ] && [ -f "$FEATURE_DIR/work-contract.json" ]; then
  CONTRACT="$FEATURE_DIR/work-contract.json"
fi

# Contract controls final profile and retry count. Explicit CLI always wins.
if [ "$FULL" = 1 ] && [ -z "$PROFILE" ]; then
  if [ -n "$CONTRACT" ]; then
    PROFILE="$(python3 - "$CONTRACT" <<'PY' 2>/dev/null || true
import json, sys
try:
    value = json.load(open(sys.argv[1], encoding='utf-8'))
    print((value.get('verification') or {}).get('profile') or '')
except Exception:
    pass
PY
)"
  fi
  [ -n "$PROFILE" ] || PROFILE="full"
fi
[ -n "$PROFILE" ] || PROFILE="fast"

if [ "$MAX_EXPLICIT" = 0 ] && [ -n "$CONTRACT" ]; then
  contract_max="$(python3 - "$CONTRACT" <<'PY' 2>/dev/null || true
import json, sys
try:
    value = json.load(open(sys.argv[1], encoding='utf-8'))
    print((value.get('retry') or {}).get('max_attempts_per_slice') or '')
except Exception:
    pass
PY
)"
  case "$contract_max" in
    ''|*[!0-9]*) : ;;
    *) MAX_ATTEMPTS="$contract_max" ;;
  esac
fi

if [ -n "$SLICE" ]; then
  if [ -z "$TASKS_FILE" ] || [ ! -f "$TASKS_FILE" ]; then
    echo "EVAL: UNAVAILABLE"
    echo "- tasks.md를 결정하지 못했다. --feature 또는 --tasks를 지정한다."
    exit 2
  fi
  if ! is_generated_tasks "$TASKS_FILE"; then
    echo "EVAL: UNAVAILABLE"
    echo "- ${TASKS_FILE#$REPO/}가 taskify 생성물이 아니다. task manifest에서 재생성한다."
    exit 2
  fi
  if ! grep -qE "^## Slice $SLICE( |$)" "$TASKS_FILE"; then
    echo "EVAL: UNAVAILABLE"
    echo "- Slice $SLICE가 없다. 사용 가능한 slice:"
    list_slices "$TASKS_FILE"
    exit 2
  fi
fi

mkdir -p "$EVIDENCE_DIR"
FAILED_FILE="${TMPDIR:-/tmp}/amplai-eval-failed.$$"
: > "$FAILED_FILE"
NFAILED=0
ENV_ERROR=0

record_failure() {
  printf '%s\n' "$1" >> "$FAILED_FILE"
  NFAILED=$((NFAILED + 1))
}

run_shell_step() {
  name="$1"
  command="$2"
  out="${TMPDIR:-/tmp}/amplai-eval-out.$$"
  echo "--- $name"
  bash -c "$command" > "$out" 2>&1
  rc=$?
  if [ -s "$out" ]; then sed 's/^/    /' "$out"; fi
  rm -f "$out"
  if [ "$rc" = 0 ]; then
    echo "    PASS"
  else
    echo "    FAIL (exit $rc)"
    record_failure "$name"
  fi
  return 0
}

echo "==== AMPLAI eval ===="
echo "repo    : $REPO"
[ -n "$FEATURE_DIR" ] && echo "feature : ${FEATURE_DIR#$REPO/}"
[ -n "$TASKS_FILE" ] && echo "tasks   : ${TASKS_FILE#$REPO/}"
[ -n "$SLICE" ] && echo "slice   : $SLICE"
echo "profile : $PROFILE"
echo "attempts: $MAX_ATTEMPTS"
echo

# Project-level deterministic checks.
VERIFIER_REPORT="$EVIDENCE_DIR/verifier-last.json"
echo "--- verifier:$PROFILE"
python3 .ai-team/verifiers/run.py --profile "$PROFILE" --json-report "$VERIFIER_REPORT"
verifier_rc=$?
case "$verifier_rc" in
  0) echo "    PASS" ;;
  1)
    echo "    FAIL"
    verifier_failed="${TMPDIR:-/tmp}/amplai-verifier-failed.$$"
    python3 - "$VERIFIER_REPORT" > "$verifier_failed" <<'PY' 2>/dev/null || true
from __future__ import print_function
import json, sys
try:
    value = json.load(open(sys.argv[1], encoding='utf-8'))
except Exception:
    value = {}
for item in value.get('results') or []:
    if item.get('severity') == 'block' and item.get('status') == 'FAIL':
        print('verifier:' + str(item.get('id') or '<unknown>'))
PY
    if [ -s "$verifier_failed" ]; then
      while IFS= read -r item; do
        [ -n "$item" ] && record_failure "$item"
      done < "$verifier_failed"
    else
      record_failure "verifier:$PROFILE"
    fi
    rm -f "$verifier_failed"
    ;;
  2) echo "    UNAVAILABLE"; ENV_ERROR=1 ;;
  *) echo "    UNAVAILABLE (unexpected exit $verifier_rc)"; ENV_ERROR=1 ;;
esac

# Slice-specific executable acceptance.
if [ -n "$SLICE" ]; then
  CMDS="$(extract_section "$TASKS_FILE" "$SLICE" "Eval")"
  if [ -z "$CMDS" ]; then
    echo "--- slice:$SLICE"
    echo "    FAIL (Eval block is empty)"
    record_failure "slice:$SLICE:no-eval-command"
  else
    commands_file="${TMPDIR:-/tmp}/amplai-eval-cmds.$$"
    printf '%s\n' "$CMDS" > "$commands_file"
    while IFS= read -r raw; do
      [ -n "$raw" ] || continue
      command="$(printf '%s' "$raw" | sed -e 's/^`//' -e 's/`$//')"
      [ -n "$command" ] || continue
      run_shell_step "slice:$SLICE:$command" "$command"
    done < "$commands_file"
    rm -f "$commands_file"
  fi
fi

echo
if [ "$ENV_ERROR" -ne 0 ]; then
  echo "EVAL: UNAVAILABLE"
  echo "- 요청한 verifier profile을 현재 환경에서 끝까지 실행하지 못했다."
  rm -f "$FAILED_FILE"
  exit 2
fi

if [ "$NFAILED" -eq 0 ]; then VERDICT="PASS"; else VERDICT="FAIL"; fi
ATTEMPT=0
FEATURE_KEY="${FEATURE_DIR#$REPO/}"
[ -n "$FEATURE_KEY" ] || FEATURE_KEY="<repository>"

if [ -n "$SLICE" ]; then
  HIST="$EVIDENCE_DIR/history.jsonl"
  HISTORY_RESULT="$(python3 - "$HIST" "$FEATURE_KEY" "$SLICE" "$VERDICT" "$FAILED_FILE" <<'PY'
from __future__ import print_function
import datetime, hashlib, io, json, os, sys
hist, feature, slice_id, verdict, failed_path = sys.argv[1:]
with io.open(failed_path, 'r', encoding='utf-8') as handle:
    failed = sorted(set(line.rstrip('\n') for line in handle if line.strip()))
signature = ''
if verdict == 'FAIL':
    signature = hashlib.sha256(('\n'.join(failed)).encode('utf-8')).hexdigest()
rows = []
if os.path.isfile(hist):
    with io.open(hist, 'r', encoding='utf-8') as handle:
        for line in handle:
            try:
                row = json.loads(line)
            except Exception:
                continue
            if row.get('feature') == feature and row.get('slice') == slice_id:
                rows.append(row)
count = 0
if verdict == 'FAIL':
    for row in reversed(rows):
        if row.get('verdict') != 'FAIL':
            break
        if row.get('signature') != signature:
            break
        count += 1
    count += 1
row = {
    'ts': datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat().replace('+00:00', 'Z'),
    'feature': feature,
    'slice': slice_id,
    'verdict': verdict,
    'attempt': count,
    'signature': signature or None,
    'failed': failed,
}
directory = os.path.dirname(hist)
if directory and not os.path.isdir(directory):
    os.makedirs(directory)
with io.open(hist, 'a', encoding='utf-8') as handle:
    handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + '\n')
print('%d %s' % (count, signature))
PY
)"
  ATTEMPT="${HISTORY_RESULT%% *}"
  FAILURE_SIGNATURE="${HISTORY_RESULT#* }"
else
  FAILURE_SIGNATURE=""
fi

python3 - "$EVIDENCE_DIR/last.json" "$FEATURE_KEY" "$SLICE" "$VERDICT" "$PROFILE" "$ATTEMPT" "$FAILURE_SIGNATURE" "$FAILED_FILE" <<'PY'
from __future__ import print_function
import datetime, io, json, os, sys, tempfile
path, feature, slice_id, verdict, profile, attempt, signature, failed_path = sys.argv[1:]
with io.open(failed_path, 'r', encoding='utf-8') as handle:
    failed = sorted(set(line.rstrip('\n') for line in handle if line.strip()))
value = {
    'schema_version': '1.0',
    'ts': datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat().replace('+00:00', 'Z'),
    'feature': feature,
    'slice': slice_id or None,
    'profile': profile,
    'verdict': verdict,
    'attempt': int(attempt or 0),
    'signature': signature or None,
    'failed': failed,
}
directory = os.path.dirname(path)
if directory and not os.path.isdir(directory):
    os.makedirs(directory)
fd, tmp = tempfile.mkstemp(prefix='.eval-', suffix='.json', dir=directory or '.')
with io.open(fd, 'w', encoding='utf-8', closefd=True) as handle:
    json.dump(value, handle, ensure_ascii=False, indent=2, sort_keys=True)
    handle.write('\n')
os.rename(tmp, path)
PY

rm -f "$FAILED_FILE"

echo "EVAL: $VERDICT"
if [ "$VERDICT" = "FAIL" ]; then
  echo
  python3 - "$EVIDENCE_DIR/last.json" <<'PY'
import json, sys
value = json.load(open(sys.argv[1], encoding='utf-8'))
for item in value.get('failed') or []:
    print('- ' + item)
PY
  if [ -n "$SLICE" ]; then
    echo
    [ -n "${FAILURE_SIGNATURE:-}" ] && echo "SIGNATURE: ${FAILURE_SIGNATURE:0:12}"
    echo "ATTEMPT: $ATTEMPT/$MAX_ATTEMPTS"
    if [ "$ATTEMPT" -ge "$MAX_ATTEMPTS" ]; then
      echo
      echo "ESCALATE: 같은 failure signature가 ${MAX_ATTEMPTS}회 연속 실패했다."
      echo "systematic-debugging으로 signature를 고정한 뒤 분류한다:"
      echo "  IMPLEMENTATION -> minimal repair"
      echo "  TASK           -> taskify"
      echo "  PLAN           -> plan"
      echo "  SPEC           -> /design"
      echo "  REQUIREMENT    -> human gate"
      echo "  ENVIRONMENT    -> BLOCKED with required evidence"
      exit 3
    fi
  fi
  exit 1
fi

[ -n "$SLICE" ] && echo "ATTEMPT: 0/$MAX_ATTEMPTS (reset)"
exit 0
